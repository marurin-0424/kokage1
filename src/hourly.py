"""時刻ごとの「行き先に依存しない量」を1箇所にまとめる（2026-08-17 新設・C36）

★ なぜ要るか（spec.md M2a・§10-0b）
  行き先を1つも決めずに時刻を出すには、行き先に依存しない量が要る。
  ① 出発地から歩ける範囲の歩道の日陰率  ② その時刻のWBGT
  ①は幾何なので計算でき、②は「入力値（いまの時刻の値）＋実測の時刻差」で当てる。

★ ②を当てないと、時刻をずらす効果を過小評価する。
  16時は日陰が増える（33.9%→72.4%）だけでなく、暑さも下がる（−1.38℃）ため。
"""

# ［事実：2026-08-17 実測 hour_pick.py］環境省 2025年8月・3地点・31日＝93サンプル。
#   同じ日の13時を基準にした WBGT の差。sd はそのばらつき（標準偏差）。
#   同日内の 13時→16時 の相関 r=0.717、回帰の残差 1.27℃。
BASE_HOUR = 13
WBGT_OFFSET = {10: -0.93, 11: -0.44, 12: -0.22, 13: 0.00,
               14: -0.35, 15: -0.60, 16: -1.38, 17: -2.48, 18: -3.85}
WBGT_SD = {10: 1.21, 11: 1.20, 12: 0.98, 13: 0.00,
           14: 1.29, 15: 1.33, 16: 1.46, 17: 1.54, 18: 1.55}

# ［事実：2026-08-17 実測 hour_pick.py］池袋駅東口から400m圏の歩道の日陰率（延長重み・%）。
#   歩行空間ネットワーク 39.9km。太陽位置は 2026-08-12 固定（spec.md §10-0 の1）。
SIDEWALK_SHADE_400 = {11: 36.9, 12: 25.5, 13: 33.9, 14: 50.8, 15: 64.3, 16: 72.4, 17: 90.2}
SIDEWALK_SHADE_ALL = {11: 33.8, 12: 26.9, 13: 35.5, 14: 47.6, 15: 57.3, 16: 66.9, 17: 84.5}

# ［事実：同上］2025年8月に WBGT が 31 以上だった時点の割合（%）。3地点・31日。
#   ★ これは「その日」ではなく去年の頻度。画面には出さない（spec.md §10-0）。
OVER31_RATE = {11: 32.3, 12: 40.9, 13: 43.0, 14: 38.7, 15: 30.1, 16: 14.0, 17: 1.1}

HOURS = (11, 12, 13, 14, 15, 16)


def wbgt_at(hour, wbgt_input, input_hour=BASE_HOUR):
    """入力されたWBGT（input_hour 時点の値）を、hour の値に換算する"""
    return round(wbgt_input + WBGT_OFFSET[hour] - WBGT_OFFSET[input_hour], 2)


def wbgt_band(hour, wbgt_input, input_hour=BASE_HOUR):
    """(中心値, ばらつき±) を返す。★ 画面には幅を必ず併記する"""
    return wbgt_at(hour, wbgt_input, input_hour), round(WBGT_SD[hour], 1)


def sidewalk_shade(hour, radius=400):
    return (SIDEWALK_SHADE_400 if radius == 400 else SIDEWALK_SHADE_ALL)[hour]
